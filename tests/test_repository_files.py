"""Runtime declarations: deploy/dokploy.json, docker-compose.yml, Dockerfile."""

import json
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SEED_ACCOUNTS = "checkorca.admin@example.com,checkorca.technician@example.com"

# The Runtime chapter of the dev-work-plan: name, kind, literal value.
RUNTIME = [
    ("SECRET_KEY", "hex32", None),
    ("FERNET_KEY", "fernet", None),
    ("DATABASE_URL", "postgres_url", None),
    ("BASE_URL", "base_url", None),
    ("ROLE", "literal", "all"),
    ("METRICS_TOKEN", "token24", None),
    ("ALLOW_PRIVATE_TARGETS", "literal", "false"),
    ("DEV_SEED", "literal", "1"),
    ("DEV_SEED_ACCOUNTS", "literal", SEED_ACCOUNTS),
    ("DEV_SEED_PASSWORD_ADMIN", "token24", None),
    ("DEV_SEED_PASSWORD_TECHNICIAN", "token24", None),
    ("DEV_DEMO_DATA", "literal", "1"),
]


def test_dokploy_manifest_equals_the_runtime_table() -> None:
    manifest = json.loads((ROOT / "deploy" / "dokploy.json").read_text())
    assert manifest["database"] == "postgres16"
    assert manifest["volumes"] == []
    found = [(e["name"], e["kind"], e.get("value")) for e in manifest["env"]]
    assert found == RUNTIME
    database = next(e for e in manifest["env"] if e["name"] == "DATABASE_URL")
    assert database["scheme"] == "postgresql+asyncpg"
    # Only literals carry a value; every secret is generated by dokploy_prepare.
    for entry in manifest["env"]:
        assert ("value" in entry) == (entry["kind"] == "literal")


def test_dokploy_browser_accounts_are_the_seed_accounts() -> None:
    manifest = json.loads((ROOT / "deploy" / "dokploy.json").read_text())
    accounts = [
        (a["email"], a["label"], a["passwordEnv"]) for a in manifest["browserAccounts"]
    ]
    assert accounts == [
        ("checkorca.admin@example.com", "admin", "DEV_SEED_PASSWORD_ADMIN"),
        (
            "checkorca.technician@example.com",
            "technician",
            "DEV_SEED_PASSWORD_TECHNICIAN",
        ),
    ]
    assert ",".join(email for email, _, _ in accounts) == SEED_ACCOUNTS


def test_compose_services_ports_limits_and_logs() -> None:
    compose = yaml.safe_load((ROOT / "docker-compose.yml").read_text())
    services = compose["services"]
    assert set(services) == {"web", "worker", "db"}
    assert services["web"]["ports"] == ["8080:8080"]
    assert services["worker"]["ports"] == ["2525:2525"]
    assert services["db"]["image"].startswith("postgres:16@sha256:")
    assert "pgdata:/var/lib/postgresql/data" in services["db"]["volumes"]
    assert "pgdata" in compose["volumes"]
    limits = {name: service["mem_limit"] for name, service in services.items()}
    assert limits == {"web": "384m", "worker": "384m", "db": "512m"}
    for service in services.values():
        assert service["logging"] == {
            "driver": "json-file",
            "options": {"max-size": "10m", "max-file": "3"},
        }
        assert "healthcheck" in service


def test_dockerfile_contract() -> None:
    dockerfile = (ROOT / "Dockerfile").read_text()
    images = re.findall(r"^FROM (\S+)", dockerfile, flags=re.MULTILINE)
    assert images[0].startswith("node:22-slim@sha256:")
    assert all(image.startswith("python:3.12-slim@sha256:") for image in images[1:])
    assert "USER 10001:10001" in dockerfile
    assert "ARG REVISION" in dockerfile
    assert "EXPOSE 8080 2525" in dockerfile
    assert "HEALTHCHECK" in dockerfile
    assert 'CMD ["python", "-m", "app", "all"]' in dockerfile
    assert "COPY LICENSE NOTICE ./" in dockerfile
    assert "THIRD_PARTY_NOTICES" in dockerfile

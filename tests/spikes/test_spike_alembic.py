"""Spike 3: the Alembic cycle up, check, down, up on PostgreSQL 16 via asyncpg.

The same cycle runs as merge gate check 3 with the alembic command line; here it
runs through the configuration python -m app migrate builds, so the async
migrations/env.py, the migration lock and the revision chain are exercised
in-process. Head and the revision below it come from the script directory, so the
spike keeps working as later phases add revisions.

The test is synchronous: env.py starts its own event loop. It downgrades one
revision, so it fails (never skips) on a database whose name does not end in
_test; CI uses checkorca_test.
"""

import asyncio
import time
from collections.abc import Callable

from alembic import command
from alembic.script import ScriptDirectory
from sqlalchemy import text
from sqlalchemy.engine import make_url
from sqlalchemy.ext.asyncio import create_async_engine
from sqlalchemy.pool import NullPool

from app.__main__ import alembic_config
from app.settings import load_settings


async def database_state(url: str) -> tuple[str, str, list[str]]:
    """Driver name, server version number and the stored Alembic revisions."""
    engine = create_async_engine(url, poolclass=NullPool)
    try:
        async with engine.connect() as connection:
            version = await connection.execute(text("SHOW server_version_num"))
            revisions = await connection.execute(
                text("SELECT version_num FROM alembic_version")
            )
            return (
                connection.dialect.driver,
                str(version.scalar_one()),
                [str(revision) for revision in revisions.scalars()],
            )
    finally:
        await engine.dispose()


def test_alembic_upgrade_check_downgrade_upgrade(
    report: Callable[..., None],
) -> None:
    settings = load_settings()
    url = settings.database_url.get_secret_value()
    # The downgrade drops the newest revision's tables: a test database only.
    database = make_url(url).database or ""
    assert database.endswith("_test"), f"refusing to downgrade {database!r}"

    config = alembic_config(settings)
    script = ScriptDirectory.from_config(config)
    head = script.get_current_head()
    assert head is not None
    revision = script.get_revision(head)
    assert revision is not None
    below = revision.down_revision
    assert below is None or isinstance(below, str)
    below_head = [] if below is None else [below]
    started = time.perf_counter()

    command.upgrade(config, "head")
    driver, server_version, revisions = asyncio.run(database_state(url))
    assert driver == "asyncpg"
    assert server_version.startswith("16")
    assert revisions == [head]

    # Raises AutogenerateDiffsDetected when the models and the database differ.
    command.check(config)

    command.downgrade(config, "-1")
    assert asyncio.run(database_state(url))[2] == below_head

    command.upgrade(config, "head")
    assert asyncio.run(database_state(url))[2] == [head]
    elapsed_ms = (time.perf_counter() - started) * 1000
    report(
        "alembic",
        driver=driver,
        server_version_num=server_version,
        head=head,
        elapsed_ms=f"{elapsed_ms:.1f}",
    )
